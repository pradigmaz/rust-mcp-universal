use serde_json::{Value, json};

use super::helpers::{json_schema_object, tool_with_output};

pub(super) fn diagnostics_tools(auto_index: &Value, privacy_mode: &Value) -> Vec<Value> {
    let counts = json_schema_object(
        &[
            ("notes", json!({"type": "integer", "minimum": 0})),
            ("decisions", json!({"type": "integer", "minimum": 0})),
            ("risks", json!({"type": "integer", "minimum": 0})),
            ("constraints", json!({"type": "integer", "minimum": 0})),
            ("artifacts", json!({"type": "integer", "minimum": 0})),
            ("relations", json!({"type": "integer", "minimum": 0})),
            ("aliases", json!({"type": "integer", "minimum": 0})),
            ("tags", json!({"type": "integer", "minimum": 0})),
            ("observations", json!({"type": "integer", "minimum": 0})),
        ],
        &[
            "notes",
            "decisions",
            "risks",
            "constraints",
            "artifacts",
            "relations",
            "aliases",
            "tags",
            "observations",
        ],
    );
    let string_array = json!({"type": "array", "items": {"type": "string"}});
    let storage_mode = json!({"type": "string", "enum": ["codex", "project"]});
    let candidate_source = json_schema_object(
        &[
            ("root", json!({"type": "string"})),
            ("canonical_paths", string_array.clone()),
        ],
        &["root", "canonical_paths"],
    );
    let inconsistencies = json_schema_object(
        &[
            ("missing_from_index", string_array.clone()),
            ("orphaned_in_index", string_array.clone()),
            ("stale_fingerprints", string_array.clone()),
            ("parse_failures", string_array.clone()),
        ],
        &[
            "missing_from_index",
            "orphaned_in_index",
            "stale_fingerprints",
            "parse_failures",
        ],
    );

    vec![
        tool_with_output(
            "memory_status",
            "Get high-level health snapshot for project memory",
            json_schema_object(
                &[
                    ("auto_index", auto_index.clone()),
                    ("privacy_mode", privacy_mode.clone()),
                ],
                &[],
            ),
            json_schema_object(
                &[
                    ("project", json!({"type": "string"})),
                    ("project_root", json!({"type": "string"})),
                    ("memory_root", json!({"type": "string"})),
                    ("storage_mode", storage_mode.clone()),
                    ("health", json!({"type": "string"})),
                    ("counts", counts.clone()),
                    ("last_sync", json!({"type": "string"})),
                    ("drift_detected", json!({"type": "boolean"})),
                    ("parser_health", json!({"type": "string"})),
                    ("index_health", json!({"type": "string"})),
                    ("issues", string_array.clone()),
                    ("recommended_action", json!({"type": "string"})),
                ],
                &[
                    "project",
                    "project_root",
                    "memory_root",
                    "storage_mode",
                    "health",
                    "counts",
                    "drift_detected",
                    "parser_health",
                    "index_health",
                    "issues",
                    "recommended_action",
                ],
            ),
            true,
            false,
            true,
        ),
        tool_with_output(
            "preflight",
            "Inspect binary, index, and runtime compatibility risks",
            json_schema_object(&[("privacy_mode", privacy_mode.clone())], &[]),
            json_schema_object(
                &[
                    ("status", json!({"type": "string"})),
                    ("project_path", json!({"type": "string"})),
                    ("project_root", json!({"type": "string"})),
                    ("memory_root", json!({"type": "string"})),
                    ("storage_mode", storage_mode.clone()),
                    ("binary_path", json!({"type": "string"})),
                    ("running_binary_version", json!({"type": "string"})),
                    ("running_binary_stale", json!({"type": "boolean"})),
                    ("supported_schema_version", json!({"type": "integer"})),
                    ("db_schema_version", json!({"type": "integer"})),
                    (
                        "same_binary_other_pids",
                        json!({"type": "array", "items": {"type": "integer", "minimum": 0}}),
                    ),
                    ("stale_process_suspected", json!({"type": "boolean"})),
                    ("safe_recovery_hint", json!({"type": "string"})),
                    ("missing_canonical_paths", string_array.clone()),
                    ("legacy_root_layout_detected", json!({"type": "boolean"})),
                    ("legacy_root_path", json!({"type": "string"})),
                    ("warnings", string_array.clone()),
                    ("errors", string_array.clone()),
                    ("binding_status", json!({"type": "string"})),
                    ("binding_source", json!({"type": "string"})),
                ],
                &[
                    "status",
                    "project_path",
                    "project_root",
                    "memory_root",
                    "storage_mode",
                    "safe_recovery_hint",
                    "warnings",
                    "errors",
                ],
            ),
            true,
            false,
            true,
        ),
        tool_with_output(
            "index_status",
            "Get derived index status and drift indicators",
            json_schema_object(
                &[
                    ("auto_index", auto_index.clone()),
                    ("privacy_mode", privacy_mode.clone()),
                ],
                &[],
            ),
            json_schema_object(
                &[
                    ("project", json!({"type": "string"})),
                    ("project_root", json!({"type": "string"})),
                    ("memory_root", json!({"type": "string"})),
                    ("storage_mode", storage_mode.clone()),
                    ("db_path", json!({"type": "string"})),
                    ("schema_version", json!({"type": "integer"})),
                    ("indexed", json!({"type": "boolean"})),
                    ("counts", counts.clone()),
                    ("last_sync", json!({"type": "string"})),
                    ("drift_detected", json!({"type": "boolean"})),
                    ("fingerprint_drift_detected", json!({"type": "boolean"})),
                    (
                        "pending_markdown_files",
                        json!({"type": "integer", "minimum": 0}),
                    ),
                    ("inconsistencies", inconsistencies),
                    ("failures", string_array.clone()),
                ],
                &[
                    "project",
                    "project_root",
                    "memory_root",
                    "storage_mode",
                    "db_path",
                    "indexed",
                    "counts",
                    "drift_detected",
                    "fingerprint_drift_detected",
                    "pending_markdown_files",
                    "inconsistencies",
                    "failures",
                ],
            ),
            true,
            false,
            true,
        ),
        tool_with_output(
            "rebuild_index",
            "Rebuild the SQLite derived index from Markdown truth",
            json_schema_object(&[("privacy_mode", privacy_mode.clone())], &[]),
            json_schema_object(
                &[
                    ("rebuilt", json!({"type": "boolean"})),
                    ("indexed_files", json!({"type": "integer", "minimum": 0})),
                    ("counts", counts),
                    ("duration_ms", json!({"type": "integer", "minimum": 0})),
                    ("errors", string_array.clone()),
                ],
                &[
                    "rebuilt",
                    "indexed_files",
                    "counts",
                    "duration_ms",
                    "errors",
                ],
            ),
            false,
            true,
            true,
        ),
        tool_with_output(
            "migrate_memory_root",
            "Move legacy canonical Markdown from project root into the active memory root layout",
            json_schema_object(
                &[
                    ("target_storage_mode", storage_mode.clone()),
                    ("dry_run", json!({"type": "boolean"})),
                    ("source_root", json!({"type": "string"})),
                    ("privacy_mode", privacy_mode.clone()),
                ],
                &[],
            ),
            json_schema_object(
                &[
                    ("dry_run", json!({"type": "boolean"})),
                    ("target_storage_mode", storage_mode),
                    ("source_root", json!({"type": "string"})),
                    ("destination_root", json!({"type": "string"})),
                    ("canonical_paths", string_array.clone()),
                    (
                        "candidate_sources",
                        json!({"type": "array", "items": candidate_source}),
                    ),
                    ("destination_exists", json!({"type": "boolean"})),
                    ("destination_has_memory", json!({"type": "boolean"})),
                    ("migrated", json!({"type": "boolean"})),
                    ("rebuilt", json!({"type": "boolean"})),
                    ("deleted_source_paths", string_array.clone()),
                    ("warnings", string_array.clone()),
                ],
                &[
                    "dry_run",
                    "target_storage_mode",
                    "destination_root",
                    "canonical_paths",
                    "candidate_sources",
                    "destination_exists",
                    "destination_has_memory",
                    "migrated",
                    "rebuilt",
                    "deleted_source_paths",
                    "warnings",
                ],
            ),
            false,
            true,
            true,
        ),
    ]
}
